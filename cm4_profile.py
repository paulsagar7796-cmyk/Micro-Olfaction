"""
Step 4 of the C port: cycle counts and energy of System 2+ (and DA-ELM inference) on a Cortex-M4F,
for the portable reference (s2p.c, elm.c) and the optimised kernels (s2p_opt.c, elm_opt.c).

    python3 cm4_profile.py          # builds the firmware, runs QEMU, about 5 minutes

The firmware (firmware/bench.c with either library, compiled for a Cortex-M4F with the STM32F405 memory
map) runs under QEMU (-M netduinoplus2) with a profiling plugin (firmware/cm4/profiler/cm4prof.c) that
records the exact number of executions of every instruction and how often each branch was taken.
QEMU is not cycle-accurate, so cycles come from applying the Cortex-M4 timings (Arm Cortex-M4 Technical
Reference Manual, instruction and FPU timing tables) to that exact profile:

  data processing, MUL, long multiply, MOV, compare, IT       1 cycle
  MLA / MLS                                                   2
  UDIV / SDIV                                                 2–12 (data dependent; nominal 12)
  load single (LDR*, VLDR)                                    2, or 1 when it directly follows a load
  store single (STR*, VSTR)                                   1 (store buffer)
  LDM / STM / PUSH / POP / VLDM / VSTM / VPUSH / VPOP         1 + N registers (32-bit words)
  VADD, VSUB, VMUL, VNMUL, VNEG, VABS, VCMP, VCVT, VMOV, VMRS 1
  VMLA, VMLS, VFMA, ...                                       3
  VDIV, VSQRT                                                 14
  branch                                                      1, plus P when taken (P = 1–3; nominal 2)

Assumptions: zero-wait-state memory (code and data in SRAM, or flash behind the chip's cache with the
loop hot) and no interrupts. Reported: exact instruction counts, and cycles at P = 2 with the range from
P = 1 to P = 3 and UDIV at 2–12 cycles.

Energy = cycles × the chip's run current per MHz × supply voltage, from the vendors' datasheets
(typical values, 25 °C, CoreMark running from flash with the cache on; the most compute-like workload
both datasheets characterise):
  STM32L476   DS10198 Rev 11 (July 2024), Table 33: IDD_ALL(Run), Range 1, fHCLK = 80 MHz, ART enabled
              (cache on, prefetch off), CoreMark 136 µA/MHz; VDD = 3 V (section 6.1.2) → 408 pJ/cycle
  Apollo3     DS-A3-1p3p0 (v1.3.0, Feb 2024), Table 1203: IRUNLPFB, HFRC = 48 MHz low-power mode, flash
  Blue        with cache, buck converters on, CoreMark 10.3 µA/MHz at VDD = 3.3 V → 34.0 pJ/cycle
              (the headline "6 µA/MHz" is Table 1203's while-loop figure)

Benchmarks (firmware/bench.c), each run doing one kind of operation on real samples of Setting 1,
target Batch 7, seed 42: the front end (features + alignment), inference, inference with the
pseudo-label test, inference with pseudo-labelling, a calibration visit at 20 and 50 balanced labels,
and DA-ELM inference. Only library code is counted (s2p*.c, memcpy, elm*.c), not the harness or I/O.
The optimised DA-ELM is checked against the reference: identical predictions on both targets, and its
six output sums bit-identical to a float32 NumPy mirror of elm.c's arithmetic.
"""

