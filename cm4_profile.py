FIRMWARE = Path("firmware")
BUILD = FIRMWARE / "build"
MODES = {"front end": 0, "inference": 1, "inference + pseudo-label test": 2, "inference + pseudo-labelling": 3,
         "calibration visit": 4, "DA-ELM inference": 5}
N_SAMPLES = 1000
P_NOMINAL, P_RANGE = 2, (1, 3)
UDIV_NOMINAL, UDIV_RANGE = 12, (2, 12)


tools = F.arm_tools


def elm_weights() -> None:
    rng = np.random.default_rng(2015)
    arrays = {"elm_scale[128]": rng.uniform(0.001, 0.01, 128), "elm_shift[128]": rng.uniform(-1, 0, 128),
              "elm_centre[1000][128]": rng.uniform(-1, 1, (1000, 128)),
              "elm_width[1000]": rng.uniform(0.001, 0.05, 1000), "elm_beta[1000][6]": rng.normal(0, 1, (1000, 6))}

    def init(a: np.ndarray) -> str:
        a = np.asarray(a, np.float32)
        return "{" + ",".join(f"{v:.8e}f" for v in a) + "}" if a.ndim == 1 else "{" + ",".join(init(r) for r in a) + "}"
    lines = ["/* Random DA-ELM weights for the cycle benchmark (timing only); generated by cm4_profile.py. */"]
    lines += [f"const float {d} = {init(a)};" for d, a in arrays.items()]
    BUILD.mkdir(parents=True, exist_ok=True)
    (BUILD / "elm_weights.c").write_text("\n".join(lines) + "\n")


def build(t: dict) -> None:
    elm_weights()
    r = subprocess.run(["make", "-C", str(FIRMWARE), "cm4", f"ARM_TOOLS={t['arm']}"], capture_output=True, text=True)
    if r.returncode:
        raise RuntimeError(r.stdout[-3000:] + r.stderr[-3000:])
    for sdk in [None] + sorted(F.SDKS.glob("MacOSX*.*.sdk"), reverse=True):
        env = dict(os.environ, **({"SDKROOT": str(sdk)} if sdk else {}))
        r = subprocess.run(["make", "-C", str(FIRMWARE), "build/libcm4prof.dylib", f"QEMU_INCLUDE={t['qemu_include']}"],
                           capture_output=True, text=True, env=env)
        if r.returncode == 0:
            return
    raise RuntimeError(r.stdout + r.stderr)


def disassemble(t: dict, elf: Path) -> tuple[dict, dict, dict]:
    """address -> (size, mnemonic, operands); function name -> (start, end); branch targets."""
    text = subprocess.run([str(t["arm"] / "arm-none-eabi-objdump"), "-d", str(elf)], capture_output=True, text=True).stdout
    insn, func, targets = {}, {}, defaultdict(set)
    line_re = re.compile(r"^\s*([0-9a-f]+):\s+((?:[0-9a-f]{4}\s?){1,2})\s+(\S+)\s*(.*)$")
    for line in text.splitlines():
        m = line_re.match(line)
        if not m:
            continue
        addr, raw, mnem, ops = int(m.group(1), 16), m.group(2).split(), m.group(3), m.group(4).split(";")[0].strip()
        insn[addr] = (2 * len(raw), mnem, ops)
        tm = re.match(r"^([0-9a-f]+)\s+<", ops)
        if mnem.split(".")[0].rstrip("s") in ("b", "bl", "cbz", "cbnz") or re.match(r"^b(eq|ne|cs|cc|mi|pl|vs|vc|hi|ls|ge|lt|gt|le|hs|lo)$", mnem.split(".")[0]):
            if tm:
                targets[int(tm.group(1), 16)].add(addr)
    nm = subprocess.run([str(t["arm"] / "arm-none-eabi-nm"), "-S", "--defined-only", str(elf)],
                        capture_output=True, text=True).stdout
    for line in nm.splitlines():
        parts = line.split()
        if len(parts) == 4 and parts[2] in "tT":
            start = int(parts[0], 16) & ~1
            func[parts[3]] = (start, start + int(parts[1], 16))
    return insn, func, targets


def library_functions(t: dict) -> set[str]:
    names = set()
    for obj in ("s2p.o", "elm.o"):
        out = subprocess.run([str(t["arm"] / "arm-none-eabi-nm"), "--defined-only", str(BUILD / "cm4" / obj)],
                             capture_output=True, text=True).stdout
        names |= {p[2] for p in (l.split() for l in out.splitlines()) if len(p) == 3 and p[1] in "tT"}
    return names | {"memcpy"}


LOADS = re.compile(r"^(ldr|ldrb|ldrh|ldrsb|ldrsh|ldrex|vldr)$")
STORES = re.compile(r"^(str|strb|strh|strex|vstr)$")


def base(mnem: str) -> str:
    m = mnem.split(".")[0]
    for cond in ("eq", "ne", "cs", "cc", "mi", "pl", "vs", "vc", "hi", "ls", "ge", "lt", "gt", "le", "hs", "lo", "al"):
        if m.endswith(cond) and len(m) > len(cond) and m[:-len(cond)] in KNOWN:
            return m[:-len(cond)]
    return m


KNOWN = {"b", "bl", "bx", "blx", "cbz", "cbnz", "ldr", "ldrb", "ldrh", "ldrsb", "ldrsh", "ldrd", "str", "strb",
         "strh", "strd", "ldm", "ldmia", "ldmdb", "stm", "stmia", "stmdb", "push", "pop", "vldr", "vstr", "vldm",
         "vldmia", "vstm", "vstmia", "vstmdb", "vpush", "vpop", "vmov", "vadd", "vsub", "vmul", "vnmul", "vdiv",
         "vsqrt", "vneg", "vabs", "vcmp", "vcmpe", "vcvt", "vmrs", "vmsr", "vmla", "vmls", "vnmla", "vnmls",
         "vfma", "vfms", "vfnma", "vfnms", "mul", "mla", "mls", "umull", "smull", "umlal", "smlal", "udiv", "sdiv",
         "mov", "movs", "add", "adds", "sub", "subs", "cmp", "cmn", "it", "ite", "itt", "itte", "ittt", "itee",
         "iteee", "itet", "itete", "ittee", "itett", "ittet", "itttt", "iteet", "iteett", "tst", "and", "orr",
         "eor", "bic", "lsl", "lsr", "asr", "rsb", "adr", "neg", "mvn", "uxtb", "uxth", "sxtb", "sxth", "ubfx",
         "sbfx", "bfi", "bfc", "clz", "rev", "nop", "movw", "movt", "adc", "sbc", "ands", "orrs", "eors", "lsls",
         "lsrs", "asrs", "rsbs", "muls", "mvns", "bics", "tbb", "tbh"}


def reg_count(ops: str) -> int:
    """Number of 32-bit registers in a register list such as {r4, r5, lr} or {s16-s19} or {d8-d9}."""
    m = re.search(r"\{([^}]*)\}", ops)
    if not m:
        return 1
    n = 0
    for part in m.group(1).split(","):
        part = part.strip()
        rng = re.match(r"([rsd])(\d+)-[rsd](\d+)", part)
        k = int(rng.group(3)) - int(rng.group(2)) + 1 if rng else 1
        n += 2 * k if part.startswith("d") else k
    return n


def cost(addr: int, insn: dict, prev: dict, is_target: bool, udiv: int) -> tuple[int, str, bool]:
    """(cycles excluding a taken-branch refill, class, is a branch)."""
    size, mnem, ops = insn[addr]
    b = base(mnem)
    if b in ("b", "bl", "bx", "blx", "cbz", "cbnz", "tbb", "tbh") or re.match(r"^b(eq|ne|cs|cc|mi|pl|vs|vc|hi|ls|ge|lt|gt|le|hs|lo)$", b):
        return (2 if b in ("tbb", "tbh") else 1), "branch", True
    if b in ("pop", "ldm", "ldmia", "ldmdb") and "pc" in ops:
        return 1 + reg_count(ops), "load/store multiple", True
    if b in ("ldr",) and ops.startswith("pc"):
        return 2, "load", True
    if b in ("push", "pop", "ldm", "ldmia", "ldmdb", "stm", "stmia", "stmdb", "vpush", "vpop", "vldm", "vldmia",
             "vstm", "vstmia", "vstmdb"):
        return 1 + reg_count(ops), "load/store multiple", False
    if b in ("ldrd", "strd"):
        return 3 if b == "ldrd" else 2, "load/store", False
    if LOADS.match(b):
        p = prev.get(addr)
        pipelined = p is not None and LOADS.match(base(insn[p][1])) is not None and not is_target
        return (1 if pipelined else 2), "load", False
    if STORES.match(b):
        return 1, "store", False
    if b in ("vdiv", "vsqrt"):
        return 14, "FP divide / square root", False
    if b in ("vmla", "vmls", "vnmla", "vnmls", "vfma", "vfms", "vfnma", "vfnms"):
        return 3, "FP multiply-accumulate", False
    if b.startswith("v"):
        return (2 if b == "vmov" and ops.count(",") >= 3 else 1), "FP arithmetic / move", False
    if b in ("udiv", "sdiv"):
        return udiv, "divide", False
    if b in ("mla", "mls"):
        return 2, "multiply", False
    if b in ("mul", "muls", "umull", "smull", "umlal", "smlal"):
        return 1, "multiply", False
    return 1, "integer", False


def cycles(profile: np.ndarray, insn: dict, func: dict, targets: dict, keep: set[str]) -> dict:
    """Instruction counts and cycles for the functions in `keep`, from an execution profile."""
    owner = {}
    for name, (s, e) in func.items():
        if name in keep:
            for a in insn:
                if s <= a < e:
                    owner[a] = name
    addrs = sorted(insn)
    prev = {a: p for p, a in zip(addrs, addrs[1:]) if owner.get(a) is not None and owner.get(a) == owner.get(p)}
    out = {"instructions": 0, "taken": 0, "udiv": 0, "by_function": defaultdict(lambda: np.zeros(3)),
           "by_class": defaultdict(float), "cycles": np.zeros(3)}
    for addr, n, taken in profile:
        if addr not in owner:
            continue
        c, cls, is_branch = cost(addr, insn, prev, addr in targets, UDIV_NOMINAL)
        lo_c, _, _ = cost(addr, insn, prev, addr in targets, UDIV_RANGE[0])
        refill = taken if is_branch else 0
        trio = np.array([lo_c * n + refill * P_RANGE[0], c * n + refill * P_NOMINAL, c * n + refill * P_RANGE[1]], float)
        out["instructions"] += int(n)
        out["taken"] += int(refill)
        out["by_function"][owner[addr]] += trio
        out["by_class"][cls] += trio[1]
        out["cycles"] += trio
    return out


def run_bench(t: dict, sc: R.Scenario, mode: int, count: int, tmp: Path) -> tuple[np.ndarray, str, bytes]:
    scen = tmp / "scenario.bin"
    F.write_scenario(sc, R.CHIP32_DEVICE, tmp / "body.bin")
    scen.write_bytes(np.array([mode, count], np.int32).tobytes() + (tmp / "body.bin").read_bytes())
    elf = (BUILD / "cm4_bench.elf").resolve()
    text = subprocess.run([str(t["arm"] / "arm-none-eabi-objdump"), "-h", str(elf)], capture_output=True, text=True).stdout
    sec = {m.group(1): (int(m.group(3), 16), int(m.group(2), 16))
           for m in re.finditer(r"^\s*\d+\s+(\.\w+)\s+([0-9a-f]+)\s+([0-9a-f]+)", text, re.M)}
    lo, size = sec[".text"]
    prof = tmp / "profile.bin"
    plugin = f"{(BUILD / 'libcm4prof.dylib').resolve()},lo={lo},hi={lo + size},out={prof}"
    r = subprocess.run(F.qemu_command(t["qemu"], elf, ["-plugin", plugin]), cwd=tmp, capture_output=True, text=True,
                       timeout=3600)
    if r.returncode:
        raise RuntimeError(r.stdout + r.stderr)
    # QEMU writes the semihosting console (the firmware's stack report) to stderr
    return np.fromfile(prof, np.uint64).reshape(-1, 3), r.stdout + r.stderr, (tmp / "output.bin").read_bytes()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument("--samples", type=int, default=N_SAMPLES)
    parser.add_argument("--out", type=Path, default=Path("results/cm4_cycles.csv"))
    args = parser.parse_args()
    t = tools()
    build(t)
    insn, func, targets = disassemble(t, BUILD / "cm4_bench.elf")
    keep = library_functions(t)
    runs = [(name, mode, 20) for name, mode in MODES.items()] + [("calibration visit", MODES["calibration visit"], 50)]
    rows, results = [], {}
    for name, mode, labels in runs:
        sc = R.settings_scenario(1, 7, 42, labels, "balanced", 3.0, True, True)
        with tempfile.TemporaryDirectory() as tmp:
            prof, stdout, output = run_bench(t, sc, mode, args.samples, Path(tmp))
        res = cycles(prof, insn, func, targets, keep)
        updates = int(np.frombuffer(output[-4:], np.int32)[0])
        stack = int(re.search(r"stack_max_bytes=(\d+)", stdout).group(1))
        key = f"{name}" + (f" ({labels} labels)" if mode == MODES["calibration visit"] else "")
        results[key] = dict(res, updates=updates, stack=stack)
        lo_c, nom, hi_c = res["cycles"]
        rows.append({"run": key, "samples": 0 if mode == MODES["calibration visit"] else args.samples,
                     "labels": labels if mode == MODES["calibration visit"] else 0, "instructions": res["instructions"],
                     "taken_branches": res["taken"], "cycles_nominal": nom, "cycles_min": lo_c, "cycles_max": hi_c,
                     "pseudo_updates": updates, "stack_max_bytes": stack})
        print(f"{key:<36} {res['instructions']:>12,} instructions {nom:>14,.0f} cycles ({lo_c:,.0f}–{hi_c:,.0f})"
              f"  updates {updates}  stack {stack} B")
    df = pd.DataFrame(rows)
    args.out.parent.mkdir(exist_ok=True)
    df.to_csv(args.out, index=False)

    n = args.samples
    per = {k: v["cycles"] for k, v in results.items()}
    front = per["front end"] / n
    infer = per["inference"] / n
    test = (per["inference + pseudo-label test"] - per["inference"]) / n
    upd_n = results["inference + pseudo-labelling"]["updates"]
    update = (per["inference + pseudo-labelling"] - per["inference + pseudo-label test"]) / max(upd_n, 1)
    elm = per["DA-ELM inference"] / n
    print("\nPer operation (cycles at P = 2; range P = 1–3, UDIV 2–12):")
    for label, v in (("front end (features + alignment), per sample", front),
                     ("scores + argmax, per sample", infer - front),
                     ("inference, per sample", infer), ("pseudo-label confidence test, per sample", test),
                     (f"pseudo-label update, per update ({upd_n} updates)", update),
                     ("calibration visit, 20 labels", per["calibration visit (20 labels)"]),
                     ("calibration visit, 50 labels", per["calibration visit (50 labels)"]),
                     ("DA-ELM inference, per sample", elm)):
        print(f"  {label:<52}{v[1]:>14,.0f}   ({v[0]:,.0f}–{v[2]:,.0f})")
    passes = {"s2p_calibrate", "s2p_partial_fit", "fisher_yates", "s2p_expf"}
    for labels in (20, 50):
        bf = results[f"calibration visit ({labels} labels)"]["by_function"]
        only = sum((v for f, v in bf.items() if f in passes), np.zeros(3))
        print(f"  {'  of which the 50 calibration passes, ' + str(labels) + ' labels':<52}{only[1]:>14,.0f}   "
              f"({only[0]:,.0f}–{only[2]:,.0f})")
    seq = pd.read_csv("results/sequential_system2plus.csv")
    seq = seq[(seq.condition == "System 2+") & (seq.budget == 12)]
    rate = seq.pseudo_updates.sum() / seq.scored.sum()
    deployed = infer + test + rate * update
    print(f"  {'deployed average per sample (updates at ' + f'{100 * rate:.1f} %' + ' of samples)':<52}"
          f"{deployed[1]:>14,.0f}   ({deployed[0]:,.0f}–{deployed[2]:,.0f})")
    print(f"  DA-ELM / System 2+ inference with the pseudo-label test: {elm[1] / (infer[1] + test[1]):.1f}×; "
          f"DA-ELM / deployed average: {elm[1] / deployed[1]:.1f}×")
    by_class = results["inference"]["by_class"]
    total = sum(by_class.values())
    print("\nInference cycles by instruction class: " + ", ".join(f"{k} {100 * v / total:.0f} %" for k, v in
                                                                  sorted(by_class.items(), key=lambda kv: -kv[1])))
    print(f"Library stack, deepest call chain (compiler frame sizes, 50 labelled samples): {library_stack()} bytes; "
          f"measured peak of the whole benchmark program: {max(v['stack'] for v in results.values())} bytes")
    print(f"wrote {args.out}")


CALL_CHAINS = [("s2p_calibrate", "s2p_partial_fit", "s2p_expf"), ("s2p_classify", "s2p_partial_fit", "s2p_expf"),
               ("s2p_classify", "s2p_decision"), ("s2p_features", "s2p_logf"), ("s2p_align",),
               ("s2p_add_labelled", "memcpy")]


def library_stack() -> int:
    """Deepest chain of the library's API calls, from -fstack-usage frame sizes (memcpy's frame: 0-8 B)."""
    frames = {"memcpy": 8}
    for line in (BUILD / "s2p_cm4_50.su").read_text().splitlines():
        loc, size = line.split("\t")[:2]
        frames[loc.split(":")[-1]] = int(size)
    return max(sum(frames.get(f, 0) for f in chain) for chain in CALL_CHAINS)


if __name__ == "__main__":
    main()
